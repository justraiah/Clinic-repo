
using Capstone_Clinic.Data;
using Capstone_Clinic.Helpers;
using Capstone_Clinic.Models;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;
using Microsoft.EntityFrameworkCore;
using System.ComponentModel.DataAnnotations;

namespace Capstone_Clinic.Pages.VitalSignLogPages
{
    public class ReassessmentModel : PageModel
    {
        private readonly AppDbContext _context;

        public ReassessmentModel(AppDbContext context)
        {
            _context = context;
        }

        // IDs are populated from the database, not trusted from the form.
        public int VitalSignLogId { get; set; }
        public int MedicalRecordId { get; set; }

        // Original Pre-consultation readings (read-only)
        public double Temperature { get; set; }
        public int HeartRate { get; set; }
        public int RespiratoryRate { get; set; }
        public int OxygenSaturation { get; set; }
        public int SystolicBP { get; set; }
        public int DiastolicBP { get; set; }
        public DateTime RecordedAt { get; set; }

        // Post-consultation readings
        [BindProperty]
        [Required(ErrorMessage = "Post temperature is required.")]
        [Range(20.0, 50.0)]
        public double? PostTemperature { get; set; }

        [BindProperty]
        [Required(ErrorMessage = "Post heart rate is required.")]
        [Range(1, 300)]
        public int? PostHeartRate { get; set; }

        [BindProperty]
        [Required(ErrorMessage = "Post respiratory rate is required.")]
        [Range(1, 100)]
        public int? PostRespiratoryRate { get; set; }

        [BindProperty]
        [Required(ErrorMessage = "Post oxygen saturation is required.")]
        [Range(1, 100)]
        public int? PostOxygenSaturation { get; set; }

        [BindProperty]
        [Required(ErrorMessage = "Post systolic BP is required.")]
        [Range(20, 300)]
        public int? PostSystolicBP { get; set; }

        [BindProperty]
        [Required(ErrorMessage = "Post diastolic BP is required.")]
        [Range(20, 200)]
        public int? PostDiastolicBP { get; set; }

        public async Task<IActionResult> OnGetAsync(int id)
        {
            var vital = await _context.VitalSignLogs
                .FirstOrDefaultAsync(v => v.VitalSignLogId == id);

            if (vital == null)
                return NotFound();

            LoadPreReadings(vital);

            // If a reassessment already exists, display its saved values.
            PostTemperature = vital.PostTemperature;
            PostHeartRate = vital.PostHeartRate;
            PostRespiratoryRate = vital.PostRespiratoryRate;
            PostOxygenSaturation = vital.PostOxygenSaturation;
            PostSystolicBP = vital.PostSystolicBP;
            PostDiastolicBP = vital.PostDiastolicBP;

            return Page();
        }

        public async Task<IActionResult> OnPostAsync(int id)
        {
            var vital = await _context.VitalSignLogs
                .FirstOrDefaultAsync(v => v.VitalSignLogId == id);

            if (vital == null)
                return NotFound();

            // Always reload original Pre readings from the database.
            LoadPreReadings(vital);

            if (!ModelState.IsValid)
                return Page();

            // Update ONLY the Post readings.
            vital.PostTemperature = PostTemperature;
            vital.PostHeartRate = PostHeartRate;
            vital.PostRespiratoryRate = PostRespiratoryRate;
            vital.PostOxygenSaturation = PostOxygenSaturation;
            vital.PostSystolicBP = PostSystolicBP;
            vital.PostDiastolicBP = PostDiastolicBP;

            // Re-evaluate the original record using Pre and Post readings.
            VitalSignEvaluator.Evaluate(vital);

            // Retrieve alerts already associated with this vital-sign record.
            var existingAlerts = await _context.Alerts
                .Where(a => a.VitalLogId == vital.VitalSignLogId)
                .OrderByDescending(a => a.CreatedAt)
                .ToListAsync();

            // Separate the Pre and Post remarks generated by the evaluator.
            var allRemarks = (vital.Remarks ?? "")
                .Split(',', StringSplitOptions.RemoveEmptyEntries)
                .Select(r => r.Trim())
                .ToList();

            var preFindings = allRemarks
                .Where(r => r.StartsWith("Pre:"))
                .ToList();

            var postFindings = allRemarks
                .Where(r => r.StartsWith("Post:"))
                .ToList();

            string initialFindings = preFindings.Any()
                ? string.Join(", ", preFindings)
                : "No initial threshold abnormalities detected";

            string reassessmentFindings = postFindings.Any()
                ? string.Join(", ", postFindings)
                : "No post-rest threshold abnormalities detected";

            // Build the reassessment summary.
            string reassessmentSummary =
                $"Initial findings: {initialFindings}. " +
                $"Post-rest readings: Temperature {PostTemperature:F1} °C, " +
                $"Pulse Rate {PostHeartRate} BPM, " +
                $"Respiratory Rate {PostRespiratoryRate} breaths/min, " +
                $"SpO₂ {PostOxygenSaturation}%, " +
                $"Blood Pressure {PostSystolicBP}/{PostDiastolicBP} mmHg. " +
                $"Reassessment findings: {reassessmentFindings}. " +
                $"Overall status remains {vital.Status}.";

            // Find the existing alert for this record.
            var alert = existingAlerts.FirstOrDefault();

            // Create an alert if the record is abnormal but has none yet.
            if (alert == null && vital.Status != "Normal")
            {
                alert = new Alert
                {
                    VitalLogId = vital.VitalSignLogId,
                    CreatedAt = DateTime.Now
                };

                _context.Alerts.Add(alert);
                existingAlerts.Add(alert);
            }

            // Update alert details if an alert exists.
            if (alert != null)
            {
                alert.AlertType = vital.Status;
                alert.AlertMessage = reassessmentSummary;
            }

            // Reassessment successfully completed.
            // Resolve all alerts associated with this vital-sign record,
            // regardless of whether they were Active or Acknowledged.
            foreach (var existingAlert in existingAlerts)
            {
                existingAlert.Status = "Resolved";
            }

            await _context.SaveChangesAsync();

            if (vital.Status == "Critical")
            {
                TempData["CriticalAlertMessage"] =
                    "Critical vital-sign readings detected during reassessment. Please review the patient immediately.";
            }

            // Return to the same patient's Vital Signs History.
            return RedirectToPage("./Index", new
            {
                medicalRecordId = vital.MedicalRecordId
            });
        }

        private void LoadPreReadings(VitalSignLog vital)
        {
            VitalSignLogId = vital.VitalSignLogId;
            MedicalRecordId = vital.MedicalRecordId;

            Temperature = vital.Temperature;
            HeartRate = vital.HeartRate;
            RespiratoryRate = vital.RespiratoryRate;
            OxygenSaturation = vital.OxygenSaturation;
            SystolicBP = vital.SystolicBP;
            DiastolicBP = vital.DiastolicBP;
            RecordedAt = vital.RecordedAt;
        }
    }
}
